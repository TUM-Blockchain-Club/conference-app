// Supabase URL/key come from local.properties, which is gitignored, so no
// real project value ever hits git.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun supabaseSetting(propertyKey: String, default: String): String = localProperties.getProperty(propertyKey) ?: default

val supabaseUrl = supabaseSetting("supabase.url", "https://your-project-ref.supabase.co")
val supabasePublishableKey = supabaseSetting("supabase.publishableKey", "sb_publishable_replace_me")

val generateSupabaseConfig = tasks.register("generateSupabaseConfig") {
    val outputDir = layout.buildDirectory.dir("generated/supabaseConfig/commonMain/kotlin")
    // Without these the task has outputs but no inputs, so Gradle calls it
    // UP-TO-DATE forever and editing local.properties silently keeps the old
    // (often placeholder) values baked into the build.
    inputs.property("supabaseUrl", supabaseUrl)
    inputs.property("supabasePublishableKey", supabasePublishableKey)
    outputs.dir(outputDir)
    doLast {
        val file = outputDir.get().asFile.resolve("com/conference/asmara/config/SupabaseConfig.kt")
        file.parentFile.mkdirs()
        file.writeText(
            """
            package com.conference.asmara.config

            // Generated by the :shared:generateSupabaseConfig Gradle task from local.properties.
            // See README.md#supabase. Do not edit directly; do not commit this file's real values.
            object SupabaseConfig {
                const val URL = "$supabaseUrl"
                const val PUBLISHABLE_KEY = "$supabasePublishableKey"
            }
            """.trimIndent(),
        )
    }
}

// Push notifications are credential-optional (#7): every `make` target has to
// build and pass with no Firebase project and no Apple Developer account. Each
// platform turns push on only when its Firebase config file is present, and
// `push.enabled=false` in local.properties turns it off even then. The flag is
// generated per platform, not in commonMain, because the two halves become
// deliverable independently — an Android-only Firebase setup must not switch
// on an iOS path that has no APNs key behind it.
val pushOptedOut = localProperties.getProperty("push.enabled")?.toBoolean() == false
val androidPushEnabled = rootProject.file("androidApp/google-services.json").exists() && !pushOptedOut
val iosPushEnabled = rootProject.file("iosApp/iosApp/GoogleService-Info.plist").exists() && !pushOptedOut

fun registerPushConfig(sourceSet: String, enabled: Boolean) =
    tasks.register("generatePushConfig${sourceSet.replaceFirstChar(Char::uppercase)}") {
        val outputDir = layout.buildDirectory.dir("generated/pushConfig/$sourceSet/kotlin")
        // Not optional — see the same line on generateSupabaseConfig. Without
        // it, adding google-services.json would leave push off until a clean.
        inputs.property("pushEnabled", enabled)
        outputs.dir(outputDir)
        doLast {
            val file = outputDir.get().asFile.resolve("com/conference/asmara/push/PushConfig.kt")
            file.parentFile.mkdirs()
            file.writeText(
                """
                package com.conference.asmara.push

                // Generated by the :shared:generatePushConfig* Gradle tasks. Do not edit.
                // True only when this platform's Firebase config file exists. Read in
                // exactly one place: the platform Koin module, which binds
                // NoOpPushRegistrar when it is false.
                object PushConfig {
                    const val ENABLED = $enabled
                }
                """.trimIndent(),
            )
        }
    }

